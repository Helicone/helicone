import { Body, Controller, Post, Request, Route, Security, Tags } from "tsoa";
import { Result, err, ok } from "../../packages/common/result";
import { type JawnAuthenticatedRequest } from "../../types/request";

import {
  generateHeliconeAPIKey,
  sweepExpiredTempKeys,
} from "../../lib/experiment/tempKeys/tempAPIKey";
import {
  createPendingPiSession,
  redeemPiSession,
} from "../../lib/stores/piSessionStore";

// Unauthenticated device-link endpoints for the Helicone PI display. See
// lib/stores/piSessionStore.ts for the flow.
@Route("/v1/public/pi")
@Tags("PI")
@Security("api_key")
export class PiPublicController extends Controller {
  /**
   * Starts a device-link session. The session id is generated by the server;
   * the device shows it to the user, who links it while signed in.
   */
  @Post("/session")
  public async createSession(
    @Request() request: JawnAuthenticatedRequest
  ): Promise<Result<{ sessionUUID: string }, string>> {
    const sessionUUID = await createPendingPiSession();
    this.setStatus(201);
    return ok({ sessionUUID });
  }

  /**
   * Redeems a linked session once for a short-lived, write-only API key.
   */
  @Post("/get-api-key")
  public async getApiKey(
    @Body()
    body: {
      sessionUUID: string;
    },
    @Request() request: JawnAuthenticatedRequest
  ): Promise<Result<{ apiKey: string }, string>> {
    const session = await redeemPiSession(body.sessionUUID);
    if (session.error !== null) {
      this.setStatus(404);
      return err("Session not found");
    }

    sweepExpiredTempKeys().catch((e) =>
      console.error("Error sweeping expired temp keys:", e)
    );

    // Write-only and temporary (swept after a short TTL). It carries the user
    // who linked the device.
    const apiKey = await generateHeliconeAPIKey(
      session.data.organizationId,
      { kind: "actor", userId: session.data.userId },
      "Auto Generated PI Key",
      "w"
    );

    if (apiKey.error) {
      this.setStatus(500);
      return err("Failed to generate API key");
    }
    this.setStatus(200);
    return ok({ apiKey: apiKey.data!.apiKey });
  }
}
